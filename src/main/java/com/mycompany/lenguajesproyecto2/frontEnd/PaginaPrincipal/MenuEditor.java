    private DefaultMutableTreeNode crearNodoDesdeCarpeta(java.io.File carpeta) {
        // Creamos el nodo con el nombre de la carpeta actual
        DefaultMutableTreeNode nodoCarpeta = new DefaultMutableTreeNode(carpeta.getName());

        File[] archivos = carpeta.listFiles();
        if (archivos != null) {
            for (File archivo : archivos) {
                if (archivo.isDirectory()) {
                    nodoCarpeta.add(crearNodoDesdeCarpeta(archivo));
                } else if (archivo.getName().toLowerCase().endsWith(".pz")) {
                    // AQUÍ ESTÁ EL CAMBIO: Guardamos el objeto File completo dentro del nodo
                    nodoCarpeta.add(new DefaultMutableTreeNode(new ItemArchivo(archivo)));
                }
            }
        }
        return nodoCarpeta;
    }

