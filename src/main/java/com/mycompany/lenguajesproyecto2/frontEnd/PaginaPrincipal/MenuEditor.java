    private void escritorDePz(String phat) {
        File archivo = new File(phat);
        jtaEditor.setText("");
        try (BufferedReader lectorPrincipal = new BufferedReader(new FileReader(archivo))) {
            String linea;
            while ((linea = lectorPrincipal.readLine()) != null) {
                jtaEditor.append(linea + "\n");
            }
        } catch (IOException e) {
            Configuraciones.pantallaDeError("Error", "Error al leer el archivo: " + e.getMessage());
        }
    }

    private void configurarArbolProyecto() {
        // 1. Crear nodos
        DefaultMutableTreeNode raiz = new DefaultMutableTreeNode("PromptzalProject");
        DefaultMutableTreeNode src = new DefaultMutableTreeNode("src");
        src.add(new DefaultMutableTreeNode("main.pz"));
        src.add(new DefaultMutableTreeNode("data.pz"));

        raiz.add(src);

        jtreeCarpetas.setModel(new javax.swing.tree.DefaultTreeModel(raiz));
    }

    private DefaultMutableTreeNode crearNodoDesdeCarpeta(java.io.File carpeta) {
        // Creamos el nodo con el nombre de la carpeta actual
        DefaultMutableTreeNode nodoCarpeta = new DefaultMutableTreeNode(carpeta.getName());

        File[] archivos = carpeta.listFiles();
        if (archivos != null) {
            for (File archivo : archivos) {
                if (archivo.isDirectory()) {
                    nodoCarpeta.add(crearNodoDesdeCarpeta(archivo));
                } else if (archivo.getName().toLowerCase().endsWith(".pz")) {
                    // AQUÍ ESTÁ EL CAMBIO: Guardamos el objeto File completo dentro del nodo
                    nodoCarpeta.add(new DefaultMutableTreeNode(new ItemArchivo(archivo)));
                }
            }
        }
        return nodoCarpeta;
    }

