    private void crearArchivoActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_crearArchivoActionPerformed
        JFileChooser fileChooser = new JFileChooser();
        int resultado = fileChooser.showSaveDialog(this);

        if (resultado == JFileChooser.APPROVE_OPTION) {
            File nuevoArchivo = fileChooser.getSelectedFile();
            String nombreArchivo = nuevoArchivo.getName();
            if (!nombreArchivo.endsWith(".pz")) {
                nombreArchivo += ".pz";
            }
            DefaultTreeModel modeloArbol = (DefaultTreeModel) jtreeCarpetas.getModel();
            DefaultMutableTreeNode raiz = (DefaultMutableTreeNode) modeloArbol.getRoot();
            DefaultMutableTreeNode nodoNuevo = new DefaultMutableTreeNode(nombreArchivo);

            raiz.add(nodoNuevo);
            modeloArbol.reload();

            jtaEditor.setText("// Nuevo archivo Promptzal\n");
        }
    }// GEN-LAST:event_crearArchivoActionPerformed

    private void guardarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_guardarActionPerformed
        JFileChooser fileChooser = new JFileChooser();

        fileChooser.setFileFilter(new FileNameExtensionFilter("Archivos PromptZal (*.pz)", "pz"));

        int resultado = fileChooser.showSaveDialog(this);

        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = fileChooser.getSelectedFile();
            String rutaArchivo = archivo.getAbsolutePath();
            if (!rutaArchivo.endsWith(".pz")) {
                archivo = new File(rutaArchivo + ".pz");
            }

            try (FileWriter fileWriter = new FileWriter(archivo); PrintWriter writer = new PrintWriter(fileWriter)) {
                writer.print(jtaEditor.getText());
                Configuraciones.mensajeSi("Guardado", "Archivo guardado exitosamente en: " + archivo.getAbsolutePath());
            } catch (IOException e) {
                Configuraciones.pantallaDeError("Error Guardado", "Error al intentar guardar el archivo.");
                e.printStackTrace();
            }
        }

    }// GEN-LAST:event_guardarActionPerformed

    private void copilarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_copilarActionPerformed
        String codigoFuente = jtaEditor.getText();
        if (codigoFuente == null || codigoFuente.trim().isEmpty()) {
            Configuraciones.pantallaDeError("Advertencia",
                    "El editor está vacío. Ingrese código Promptzal para compilar.");
            return;
        }

        try {
            PromptzalLexer lexer = new PromptzalLexer(new StringReader(codigoFuente));
            while (lexer.yylex() != null) {
                // Escaneo y almacenamiento secuencial de tokens
            }

            List<TokenEntidad> tokens = lexer.getListaDeTokens();
            List<ErrorLexico> erroresLexicos = lexer.getErroresLexicos();

            if (!erroresLexicos.isEmpty()) {
                mostrarPestanaErrores(erroresLexicos, Collections.emptyList(), Collections.emptyList());

                StringBuilder sb = new StringBuilder();
                sb.append("====================================================\n");
                sb.append("   ERRORES LÉXICOS DETECTADOS (").append(erroresLexicos.size()).append(")\n");
                sb.append("====================================================\n\n");
                for (ErrorLexico err : erroresLexicos) {
                    sb.append("• ").append(err.toString()).append("\n");
                }
                mostrarPestanaPromptzal(sb.toString());
                Configuraciones.pantallaDeError("Error Léxico",
                        "Se detectaron errores léxicos en el código.\nConsulte la pestaña 'Errores Reportados'.");
                return;
            }

            PromptzalParser parser = new PromptzalParser(tokens);
            NodoPrograma ast = parser.parsearAST();

            if (ast == null || parser.tieneErrores()) {
                List<ErrorSintactico> listaErrores = parser.getErrores();
                mostrarPestanaErrores(Collections.emptyList(), listaErrores, Collections.emptyList());

                StringBuilder sb = new StringBuilder();
                sb.append("====================================================\n");
                sb.append("   ERRORES SINTÁCTICOS DETECTADOS (").append(listaErrores.size()).append(")\n");
                sb.append("====================================================\n\n");
                for (ErrorSintactico err : listaErrores) {
                    sb.append("• ").append(err.toString()).append("\n");
                }
                mostrarPestanaPromptzal(sb.toString());
                Configuraciones.pantallaDeError("Error Sintáctico",
                        "Se detectaron errores sintácticos en el código.\nConsulte la pestaña 'Errores Reportados'.");
                return;
            }

            // 3. ANÁLISIS SEMÁNTICO Y GENERACIÓN DE PROMPTZAL
            AnalizadorSemantico semantico = new AnalizadorSemantico();
            boolean semanticaValida = semantico.analizar(ast);

            if (!semanticaValida) {
                List<ErrorSemantico> erroresSem = semantico.getErrores();
                mostrarPestanaErrores(Collections.emptyList(), Collections.emptyList(), erroresSem);

                StringBuilder sb = new StringBuilder();
                sb.append("====================================================\n");
                sb.append("   ERRORES SEMÁNTICOS DETECTADOS (").append(erroresSem.size()).append(")\n");
                sb.append("====================================================\n\n");
                for (ErrorSemantico err : erroresSem) {
                    sb.append("• ").append(err.toString()).append("\n");
                }
                mostrarPestanaPromptzal(sb.toString());
                Configuraciones.pantallaDeError("Error Semántico",
                        "Se detectaron " + erroresSem.size() + " error(es) semántico(s) en el código.\nConsulte la pestaña 'Errores Reportados'.");
                return;
            }

            // COMPILACIÓN COMPLETA EXITOSA (Léxico, Sintáctico y Semántico)
            mostrarPestanaErrores(Collections.emptyList(), Collections.emptyList(), Collections.emptyList());

            String promptFinal = BibliotecaGeneradorPromptZal.generarPromptFinal(
                    ast, semantico.getTablaDeSimbolos(), semantico.getAgentesEjecutados());
            mostrarPestanaPromptzal(promptFinal);

            Configuraciones.mensajeSi("Compilación Exitosa",
                    "¡Código validado léxica, sintáctica y semánticamente con éxito!\nPromptZal generado correctamente.");
        } catch (Exception e) {
            Configuraciones.pantallaDeError("Error", "Error durante el análisis: " + e.getMessage());
            e.printStackTrace();
        }
    }// GEN-LAST:event_copilarActionPerformed

