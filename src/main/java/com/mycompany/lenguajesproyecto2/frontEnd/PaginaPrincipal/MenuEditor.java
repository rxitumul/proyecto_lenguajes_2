    private void reportesHtmlActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_reportesHtmlActionPerformed
        String codigoFuente = jtaEditor.getText();
        if (codigoFuente == null || codigoFuente.trim().isEmpty()) {
            Configuraciones.pantallaDeError("Advertencia",
                    "El editor está vacío. Ingrese código Promptzal para generar reportes.");
            return;
        }

        try {
            PromptzalLexer lexer = new PromptzalLexer(new StringReader(codigoFuente));
            while (lexer.yylex() != null) {
            }

            List<TokenEntidad> tokens = lexer.getListaDeTokens();
            List<ErrorLexico> erroresLexicos = lexer.getErroresLexicos();
            BibliotecaDeTokens biblioteca = lexer.getBiblioteca();

            // 1. Reporte HTML de Tokens usando BibliotecaDeTokens
            ReporteHTMLTabla reporteTabla = new ReporteHTMLTabla();
            for (TokenEntidad tok : tokens) {
                if (!tok.getTipo().equals("EOF") && !tok.getTipo().equals("ERROR_LEXICO")) {
                    String tipoCat = biblioteca.mapeadorDeTokens(tok.getDescripcion());
                    if ("DESCONOCIDO".equals(tipoCat)) {
                        tipoCat = tok.getTipo();
                    }
                    String desc = biblioteca.getDescripcion(tok.getDescripcion());
                    reporteTabla.registroDeTokens(new RegistroDeTokens(
                            tok.getDescripcion(),
                            tipoCat,
                            desc,
                            tok.getFila(),
                            tok.getColumna(),
                            tok.getTipo()));
                }
            }
            reporteTabla.creadorDeArchivos("reportes/tokens.html", reporteTabla.generarHTMLDeTokens());

            // 4. Reporte Consolidado de Errores (Léxicos, Sintácticos y Semánticos)
            PromptzalParser parser = new PromptzalParser(tokens);
            NodoPrograma ast = parser.parsearAST();
            List<ErrorSintactico> erroresSintacticos = parser.getErrores();

            List<ErrorSemantico> erroresSemanticos = Collections.emptyList();
            AnalizadorSemantico semantico = new AnalizadorSemantico();
            if (ast != null && !parser.tieneErrores()) {
                semantico.analizar(ast);
                erroresSemanticos = semantico.getErrores();
            }

            ReporteErroresHtml repErroresComp = new ReporteErroresHtml();
            repErroresComp.crearReporte("reportes/reporte_errores.html",
                    erroresLexicos, erroresSintacticos, erroresSemanticos);

            // 5. Reporte de Tabla de Símbolos
            ReporteTablaSimbolosHtml repTablaSim = new ReporteTablaSimbolosHtml();
            repTablaSim.crearReporte("reportes/tabla_simbolos.html", semantico.getTablaDeSimbolos());

            // 6. Reporte del AST
            if (ast != null) {
                ReporteASTHtml repAst = new ReporteASTHtml();
                repAst.crearReporte("reportes/ast.html", ast);
                ReporteASTHtml.guardarDotEnArchivo("reportes/ast.dot", ast);
                mostrarPestanaAST(ast);
            }

            // 7. Salida Prompt final si no hubo errores
            if (ast != null && erroresLexicos.isEmpty() && erroresSintacticos.isEmpty() && erroresSemanticos.isEmpty()) {
                String promptTxt = BibliotecaGeneradorPromptZal.generarPromptFinal(
                        ast, semantico.getTablaDeSimbolos(), semantico.getAgentesEjecutados());
                BibliotecaGeneradorPromptZal.guardarPromptEnArchivo("salidas/prompt_final.txt", promptTxt);
            }

            Configuraciones.mensajeSi("Reportes Generados",
                    "Se generaron exitosamente los reportes obligatorios en la carpeta 'reportes':\n"
                            + "• reporte_errores.html (Léxicos, Sintácticos y Semánticos)\n"
                            + "• tabla_simbolos.html (Agentes, Variables, Ámbitos)\n"
                            + "• ast.html / ast.dot (Representación del AST)\n"
                            + "• tokens.html y estadisticas.html");

        } catch (Exception e) {
            Configuraciones.pantallaDeError("Error", "Error al generar reportes: " + e.getMessage());
            e.printStackTrace();
        }
    }// GEN-LAST:event_reportesHtmlActionPerformed

    private String generarMensajeErrorPromptzal(String fase, List<String> detallesErrores) {
        StringBuilder sb = new StringBuilder();
        sb.append("======================================================================\n");
        sb.append("   [ERROR] ERROR DE COMPILACIÓN - PROMPTZAL NO GENERADO\n");
        sb.append("======================================================================\n\n");
        sb.append("Fase con error: ").append(fase.toUpperCase()).append("\n");
        sb.append("Total de errores detectados: ").append(detallesErrores != null ? detallesErrores.size() : 0).append("\n\n");
        sb.append("El prompt final no pudo ser generado debido a los siguientes errores:\n");
        sb.append("----------------------------------------------------------------------\n");
        if (detallesErrores != null && !detallesErrores.isEmpty()) {
            for (String err : detallesErrores) {
                sb.append("• ").append(err).append("\n");
            }
        } else {
            sb.append("• Error general durante el análisis del código.\n");
        }
        sb.append("----------------------------------------------------------------------\n");
        sb.append("Acciones sugeridas:\n");
        sb.append("1. Revise los detalles en la pestaña 'Errores Reportados' o 'Terminal'.\n");
        sb.append("2. Corrija los errores en el editor de código.\n");
        sb.append("3. Vuelva a presionar 'Copilar' para generar el PromptZal.\n");
        sb.append("======================================================================\n");
        return sb.toString();
    }

